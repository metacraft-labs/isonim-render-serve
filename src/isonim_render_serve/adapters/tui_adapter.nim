type
  TuiFrameSourceProc* = proc(): ScreenBuffer {.closure, gcsafe.}
    ## Closure that returns the current screen buffer to rasterize. The
    ## launcher captures the `TerminalTestHarness` and returns its
    ## buffer on each call so the streamed frames reflect any state
    ## changes the launcher applies between frames.

  TuiFrameSource* = ref object
    bufferProc*: TuiFrameSourceProc
    cellW*, cellH*: int
    cols*, rows*: int

proc colourToRgb(c: Color): tuple[r, g, b: uint8] =
  case c.kind
  of ckDefault: (0xCCu8, 0xCCu8, 0xCCu8)
  of ckRgb: (c.r, c.g, c.b)
  of ckIndexed, ckAnsi:
    # Coarse mapping for the rare cases the demo uses; the TUI demos in
    # `isonim-examples` mostly stick with default colours.
    let idx = case c.kind
      of ckIndexed: c.indexed
      else: ord(c.ansi).uint8
    case idx mod 8
    of 0: (0x10u8, 0x10u8, 0x10u8)
    of 1: (0xCDu8, 0x31u8, 0x31u8)
    of 2: (0x4Eu8, 0x9Au8, 0x06u8)
    of 3: (0xC4u8, 0xA0u8, 0x00u8)
    of 4: (0x34u8, 0x65u8, 0xA4u8)
    of 5: (0x75u8, 0x50u8, 0x7Bu8)
    of 6: (0x06u8, 0x98u8, 0x9Au8)
    of 7: (0xD3u8, 0xD7u8, 0xCFu8)
    else: (0xCCu8, 0xCCu8, 0xCCu8)

proc paintBackground(pixels: var seq[byte]; w, h: int;
                     x0, y0, cw, ch: int; bg: tuple[r, g, b: uint8]) =
  let xe = min(x0 + cw, w)
  let ye = min(y0 + ch, h)
  for y in y0 ..< ye:
    var off = (y * w + x0) * 4
    for _ in x0 ..< xe:
      pixels[off] = bg.r
      pixels[off + 1] = bg.g
      pixels[off + 2] = bg.b
      pixels[off + 3] = 0xFFu8
      off += 4

proc paintGlyph(pixels: var seq[byte]; w, h: int;
                x0, y0, cw, ch: int; r: Rune;
                fg: tuple[r, g, b: uint8]) =
  ## Paint a single glyph centered inside a cellWidth x cellHeight cell.
  let codePoint = int(r)
  let glyph =
    if codePoint >= PrintableStart and codePoint <= PrintableEnd:
      Font8x8[codePoint - PrintableStart]
    elif codePoint == 0:
      Font8x8[0] # null -> space
    else:
      # Unknown printable / wide rune — draw a filled block so the cell
      # is visibly distinct.
      [0x00u8, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x00]
  # Center 8x8 glyph inside the cell box (cells are cell W x cell H px).
  let baseX = x0 + max(0, (cw - GlyphWidth) div 2)
  let baseY = y0 + max(0, (ch - GlyphHeight) div 2)
  for row in 0 ..< GlyphHeight:
    let bits = glyph[row]
    let py = baseY + row
    if py < 0 or py >= h: continue
    for col in 0 ..< GlyphWidth:
      if (bits and uint8(1 shl col)) != 0:
        let px = baseX + col
        if px < 0 or px >= w: continue
        let off = (py * w + px) * 4
        pixels[off] = fg.r
        pixels[off + 1] = fg.g
        pixels[off + 2] = fg.b
        pixels[off + 3] = 0xFFu8

proc renderFrame*(src: TuiFrameSource): Frame =
  ## Pull the latest screen buffer from the harness and rasterize each
  ## non-blank cell to RGBA pixels via the embedded 8x8 bitmap font.
  let cw = src.cellW
  let ch = src.cellH
  let buf = src.bufferProc()
  let cols = buf.cols
  let rows = buf.rowsCount
  let w = cols * cw
  let h = rows * ch
  var pixels = newSeq[byte](w * h * 4)
  # Default background: terminal-style near-black so contrast on white text
  # (default fg) is visible.
  for i in 0 ..< (w * h):
    let off = i * 4
    pixels[off] = 0x0Au8
    pixels[off + 1] = 0x10u8
    pixels[off + 2] = 0x1Eu8
    pixels[off + 3] = 0xFFu8
  for rIdx in 0 ..< rows:
    for cIdx in 0 ..< cols:
      let cell = buf[rIdx, cIdx]
      let bg = colourToRgb(cell.bg)
      let fg = colourToRgb(cell.fg)
      let x0 = cIdx * cw
      let y0 = rIdx * ch
      if cell.bg.kind != ckDefault:
        paintBackground(pixels, w, h, x0, y0, cw, ch, bg)
      if cell.width > 0 and cell.rune != Rune(0) and cell.rune != Rune(' '.ord):
        paintGlyph(pixels, w, h, x0, y0, cw, ch, cell.rune, fg)
  Frame(kind: fkFull,
        flags: FrameFlags(isDiff: false, isVideo: false),
        width: w, height: h, pixels: pixels)

proc close*(src: TuiFrameSource) =
  ## No-op: the launcher owns the harness lifecycle.
  discard

proc newTuiFrameSource*(bufferProc: TuiFrameSourceProc;
                       cols, rows: int;
                       cellW = 8; cellH = 12): TuiFrameSource =
  ## Construct a TUI frame source. `cols` x `rows` is the terminal
  ## geometry; `cellW` x `cellH` controls the pixel size of each cell
  ## (default 8x12 — wide enough to embed the 8x8 glyph with a bit
  ## of vertical breathing room).
  TuiFrameSource(bufferProc: bufferProc, cols: cols, rows: rows,
                 cellW: cellW, cellH: cellH)

proc toAny*(src: TuiFrameSource): AnyFrameSource =
  let captured = src
  let pixelW = src.cols * src.cellW
  let pixelH = src.rows * src.cellH
  newAnyFrameSource(pixelW, pixelH,
    renderFrameImpl = proc(): Frame {.gcsafe.} =
      {.cast(gcsafe).}: captured.renderFrame(),
    closeImpl = proc() {.gcsafe.} =
      {.cast(gcsafe).}: captured.close())
